const LOCALE_KEY = 'opendavki.locale'

function storedLocale() {
  try {
    const value = window.localStorage.getItem(LOCALE_KEY)
    if (value === 'sl' || value === 'en') return value
  } catch { /* private mode */ }
  return 'en'
}

