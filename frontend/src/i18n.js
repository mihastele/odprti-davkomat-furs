export function t(key, params = {}) {
  const text = messages[locale.value]?.[key] ?? messages.en[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, name) => (params[name] ?? '').toString())
}

export function setLocale(id) {
  const next = messages[id] ? id : 'en'
  locale.value = next
  try { window.localStorage.setItem(LOCALE_KEY, next) } catch { /* private mode */ }
  try { document.documentElement.lang = next } catch { /* not in a browser */ }
}

export function resetLocaleForTests() {
  locale.value = 'en'
  try { window.localStorage.removeItem(LOCALE_KEY) } catch { /* ignore */ }
}
